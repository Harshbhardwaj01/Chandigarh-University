CREATE TABLE IF NOT EXISTS applications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK (length(btrim(name)) > 0),
  email TEXT NOT NULL CHECK (length(btrim(email)) > 0),
  phone VARCHAR(10) NOT NULL CHECK (phone ~ '^[0-9]{10}$'),
  program VARCHAR(100) NOT NULL CHECK (length(btrim(program)) > 0),
  city TEXT NOT NULL CHECK (length(btrim(city)) > 0),
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS applications_email_unique_idx
  ON applications (LOWER(email));

CREATE INDEX IF NOT EXISTS applications_submitted_at_idx
  ON applications (submitted_at DESC);
